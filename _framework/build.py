TOKENS = ["paper", "panel", "ink", "ink-2", "line", "accent", "accent-ink", "accent-soft", "stamp", "ok", "warn", "banner", "banner-ink"]


def token_block(s):
    L, D = s["palette"]["light"], s["palette"]["dark"]
    img = s["palette"].get("img", {"img-ink": "#F4F7F6", "img-ink-2": "#C3CFCD", "img-shade": "#0C1113", "img-accent": "#5CCBBC"})
    light = " ".join(f"--{k}:{L[k]};" for k in TOKENS) + " " + " ".join(f"--{k}:{v};" for k, v in img.items())
    dark = " ".join(f"--{k}:{D[k]};" for k in TOKENS)
    f = s["fonts"]
    return (f':root{{\n  {light}\n  --f-display:{f["display"]};\n  --f-body:{f["body"]};\n  --f-mono:{f["mono"]};\n  --wrap:1180px; --r:{s.get("radius","6px")};\n}}\n'
            f'@media (prefers-color-scheme:dark){{:root:not([data-theme="light"]){{\n  {dark} color-scheme:dark}}}}\n'
            f':root[data-theme="dark"]{{\n  {dark} color-scheme:dark}}\n\n')


def load_base():
    meru = (ROOT / "meru" / "index.html").read_text()
    css = meru[meru.index("<style>") + 7: meru.index("</style>")]
    a, b = css.index(":root{"), css.index("*{box-sizing")
    css_rest = css[b:]
    css_head = css[:a]
    motion = re.findall(r"<script>(.*?)</script>", meru, re.S)[-1]
    return css_head, css_rest, motion


def build(name):
    spec = importlib.util.spec_from_file_location(name, FW / "sites" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    s = mod.SITE
    css_head, css_rest, motion = load_base()
    shared_extra = (FW / "extra.css").read_text()
    css = css_head.replace("Layout: image-led industrial site", "Layout: image-led industrial site, generated by the Sutrayaan framework") + token_block(s) + css_rest + "\n" + shared_extra + "\n" + s.get("extra_css", "")
    site_js = {k: s["js"][k] for k in s["js"]}
    site_js.update({"slug": s["slug"], "api": s["api"], "brand": s["name"]})
    env = Environment(loader=FileSystemLoader(str(FW)), autoescape=select_autoescape(["j2", "html"]))
    html = env.get_template("template.html.j2").render(
        s=s, css=css, icons=ICONS, motion_js=motion, app_js=(FW / "app.js").read_text(),
        site_json=json.dumps(site_js, ensure_ascii=False).replace("</", "<\\/"))
    out = ROOT / s["slug"] / "index.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(html)
    print(f"built {out.relative_to(ROOT)}  ({len(html)//1024} KB)")


if __name__ == "__main__":
    names = sys.argv[1:] or sorted(p.stem for p in (FW / "sites").glob("*.py"))
    for n in names:
        build(n)
